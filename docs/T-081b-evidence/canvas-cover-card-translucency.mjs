import { createRequire } from "node:module";
import { readFileSync } from "node:fs";
import { join } from "node:path";
const ROOT = "/Users/eva/Desktop/gofreight/OffiCraft-wt-T081b/frontend";
const require = createRequire(join(ROOT, "package.json"));
const { chromium } = require("playwright");
const SRC = join(ROOT, "src");
const css = ["styles/theme.css", "styles/global.css", "components/chrome.css", "components/tasks.css"]
  .map((p) => readFileSync(join(SRC, p), "utf8")).join("\n");
const browser = await chromium.launch();
const page = await browser.newPage();
await page.setViewportSize({ width: 1440, height: 600 });
await page.setContent("<body></body>");
const img = await page.evaluate(() => { const c = document.createElement("canvas");
  c.width = 40; c.height = 40; const g = c.getContext("2d");
  g.fillStyle = "#ff00ff"; g.fillRect(0,0,40,40); return c.toDataURL("image/png"); });
await page.setContent(`<style>${css}</style><div id="root"><div class="app"><div class="topbar">t</div><div class="nav-tabs">n</div><div class="app__main"><div style="background:var(--color-card);height:200px;width:400px">card</div></div></div></div>`);
await page.evaluate((uri) => { const de = document.documentElement;
  de.style.setProperty("--canvas-bg-image", `url("${uri}")`);
  de.style.setProperty("--canvas-bg-repeat", "no-repeat");
  de.style.setProperty("--canvas-bg-position", "center center");
  de.style.setProperty("--canvas-bg-size", "cover");
  de.style.setProperty("--canvas-bg-attachment", "fixed");
  for (const t of ["--color-topbar-bg","--color-nav-bg","--color-main-bg"]) de.style.setProperty(t, "rgba(25,28,36,0.35)");
  de.style.setProperty("--color-card", "rgba(36,40,50,0.45)");
}, img);
const shot = await page.screenshot();
const px = await page.evaluate(([b64,pts]) => new Promise((res)=>{ const im=new Image();
  im.onload=()=>{const c=document.createElement("canvas");c.width=im.width;c.height=im.height;
  const g=c.getContext("2d");g.drawImage(im,0,0);
  res(pts.map(([x,y])=>{const d=g.getImageData(x,y,1,1).data;
  return `#${[d[0],d[1],d[2]].map(v=>v.toString(16).padStart(2,"0")).join("")}`;}));};
  im.src="data:image/png;base64,"+b64;}), [shot.toString("base64"), [[400,200],[900,200]]]);
console.log(`card pixel ${px[0]}  (opaque card would be #242832)   beside-card ${px[1]}`);
console.log(px[0] !== "#242832" ? "CARD IS TRANSLUCENT — image shows through" : "card still opaque");
await browser.close();
